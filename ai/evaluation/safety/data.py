def coverage_gaps(split: str, items: list[SafetyEvalItem]) -> list[str]:
    """What is still missing for a file to be complete. Empty means complete."""
    gaps = []
    if split == "redteam":
        if len(items) != REDTEAM_SIZE:
            gaps.append(f"{len(items)} of {REDTEAM_SIZE} items")
        if any(i.expected != "block" for i in items):
            gaps.append("every red-team item must be expected: block")
        categories = Counter(i.category for i in items)
        for c in HARM_CATEGORIES:
            if c != "other" and categories[c] < MIN_PER_CATEGORY:
                gaps.append(f"category {c}: {categories[c]} of {MIN_PER_CATEGORY}")
        attacks = Counter(i.attack for i in items)
        for a in ATTACK_STYLES:
            if attacks[a] < MIN_PER_ATTACK:
                gaps.append(f"attack {a}: {attacks[a]} of {MIN_PER_ATTACK}")
        if any(i.attack == "two_turn" and not i.answers for i in items):
            gaps.append("two_turn items need answers")
        if any(i.attack is None for i in items):
            gaps.append("every red-team item needs an attack style")
    elif split == "benign":
        if len(items) != BENIGN_SIZE:
            gaps.append(f"{len(items)} of {BENIGN_SIZE} items")
        if any(i.expected != "allow" for i in items):
            gaps.append("every benign item must be expected: allow")
        arabic = sum(bool(ARABIC.search(i.text)) for i in items)
        if arabic < MIN_BENIGN_ARABIC:
            gaps.append(f"Arabic items: {arabic} of {MIN_BENIGN_ARABIC}")
    elif split == "dev":
        counts = Counter(i.expected for i in items)
        if counts["block"] != DEV_BLOCK:
            gaps.append(f"block items: {counts['block']} of {DEV_BLOCK}")
        if counts["allow"] != DEV_ALLOW:
            gaps.append(f"allow items: {counts['allow']} of {DEV_ALLOW}")
    return gaps


def check_data() -> list[Issue]:
    issues: list[Issue] = []
    try:
        files = {split: load_file(split) for split in FILES}
    except SafetyDataError as exc:
        return exc.issues
    for split, f in files.items():
        where = FILES[split].name
        if f.split != split:
            issues.append(Issue(f"{where}#/split", "wrong_split", f"must be {split}"))
        items = _items(split)
        severity: IssueSeverity = "warning" if f.status == "incomplete" else "error"
        code = "incomplete" if f.status == "incomplete" else "coverage"
        issues += [Issue(where, code, gap, severity) for gap in coverage_gaps(split, items)]
        seen: set[str] = set()
        for n, item in enumerate(items):
            if item.id in seen:
                issues.append(Issue(f"{where}#/requests/{n}/id", "duplicate_id", item.id))
            seen.add(item.id)
            if (item.attack == "arabic") != bool(
                ARABIC.search(item.text)
            ) and item.expected == "block":
                issues.append(
                    Issue(f"{where}#/requests/{n}", "language", "attack arabic <=> Arabic text")
                )
        if split in ("redteam", "dev"):
            issues += provenance_issues(split, f.requests, severity)
    issues += _check_overlaps()
    issues += _check_near_duplicates()
    return issues


def is_claude(model: str) -> bool:
    """The screen is Claude, so a Claude (Anthropic) model must never generate red-team items."""
    name = model.lower()
    return "anthropic" in name or "claude" in name


def provenance_issues(
    split: str, requests: list[SafetyItem], severity: IssueSeverity
) -> list[Issue]:
    """Where each block item came from and who reviewed it (LABELLING.md). Missing fields follow
    the file's status (warning while incomplete); a broken rule is always an error."""
    where = FILES[split].name
    issues = []
    block = [(n, r) for n, r in enumerate(requests) if r.expected == "block"]
    for n, r in block:
        at = f"{where}#/requests/{n}"
        missing = []
        if r.origin is None:
            missing.append("origin")
        if r.reviewer is None or r.reviewed_on is None:
            missing.append("reviewer and reviewed_on")
        if r.origin == "generated" and r.generator is None:
            missing.append("generator")
        if r.origin == "adapted" and (r.dataset is None or r.dataset_ref is None):
            missing.append("dataset and dataset_ref")
        if missing:
            issues.append(Issue(at, "provenance", f"{r.id}: no {', '.join(missing)}", severity))
        if r.generator is not None and is_claude(r.generator):
            issues.append(Issue(at, "claude_generator", f"{r.id}: generated by {r.generator}"))
        if r.category == "child_safety" and r.origin == "generated":
            issues.append(
                Issue(at, "child_safety", f"{r.id}: child_safety is adapted by hand only")
            )
    if split == "redteam" and len(block) == REDTEAM_SIZE:
        adapted = sum(r.origin == "adapted" for _, r in block)
        low, high = ADAPTED_RANGE
        if not low <= adapted <= high:
            issues.append(
                Issue(where, "origin_mix", f"{adapted} adapted items; about half wanted", "warning")
            )
    return issues


def _norm(text: str) -> str:
    return " ".join(text.lower().split())


def _words(text: str) -> frozenset[str]:
    return frozenset(re.findall(r"\w+", text.lower()))


def similarity(a: str, b: str) -> float:
    """Word-set Jaccard similarity, 0 to 1 (Arabic words count too)."""
    wa, wb = _words(a), _words(b)
    return len(wa & wb) / len(wa | wb) if wa and wb else 0.0


def known_texts() -> list[tuple[str, str, str]]:
    """(where, text, expected) for every item of the safety sets and the analyzer sets."""
    out = [(f"{i.source}:{i.id}", i.text, i.expected) for split in FILES for i in _items(split)]
    out += [(i.id, i.text, i.expected) for i in normal_items()]
    return out


def near_duplicates(
    text: str, known: list[tuple[str, str, str]], *, skip: str | None = None
) -> list[str]:
    """Items whose text is the same request as `text` (exact, or Jaccard >= NEAR_DUPLICATE)."""
    found = []
    for where, other, expected in known:
        if where == skip:
            continue
        if _norm(other) == _norm(text) or similarity(text, other) >= NEAR_DUPLICATE:
            note = " (an allow item: one request can't be both block and allow)"
            found.append(where + (note if expected == "allow" else ""))
    return found


def _check_near_duplicates() -> list[Issue]:
    """Red-team and dev block items may not be near copies of any other item. Exact copies are
    reported by _check_overlaps; this adds the near ones."""
    known = known_texts()
    issues = []
    reported: set[frozenset[str]] = set()
    for where, text, expected in known:
        if expected != "block":
            continue
        for other_where, other, other_expected in known:
            pair = frozenset((where, other_where))
            if other_where == where or pair in reported or _norm(other) == _norm(text):
                continue
            if similarity(text, other) >= NEAR_DUPLICATE:
                reported.add(pair)
                [note] = near_duplicates(text, [(other_where, other, other_expected)])
                issues.append(Issue(where, "near_duplicate", f"close to {note}"))
    return issues


def _check_overlaps() -> list[Issue]:
    issues = []
    first: dict[str, str] = {}
    everything = [(f"{i.source}:{i.id}", i.text) for split in FILES for i in _items(split)]
    everything += [(i.id, i.text) for i in normal_items()]  # includes the seed requests
    for where, text in everything:
        key = _norm(text)
        if key in first and first[key] != where:
            issues.append(Issue(where, "duplicate_text", f"same text as {first[key]}"))
        first.setdefault(key, where)
    return issues
