"""Review red-team candidates one by one (AI-06): accept, edit or reject each. Only accepted
items are written into redteam.yaml / safety-dev.yaml, with their provenance and the reviewer.

    python -m evaluation.safety review --reviewer ziad [--split redteam|dev]
    python -m evaluation.safety review --reviewer ziad --manual    # child_safety, by hand

A candidate that duplicates another item or breaks a rule can't be accepted as it is: edit it
or reject it. When every slot of the file is filled, the reviewer may set `status: draft`.
"""

import json
import re
import textwrap
from collections import Counter
from collections.abc import Callable, Sequence
from datetime import date
from pathlib import Path
from typing import Any

import yaml

from evaluation.safety.data import (
    DATASET_LICENCES,
    FILES,
    SafetyFile,
    _items,
    coverage_gaps,
    known_texts,
    load_file,
    near_duplicates,
)
from evaluation.safety.generate import (
    ATTACK_DESCRIPTIONS,
    CANDIDATES_PATH,
    Candidate,
    GeneratedQA,
    prefilter,
    read_candidates,
    write_candidates,
)
from evaluation.safety.seeds import SEEDS_PATH, read_seeds
from evaluation.safety.slots import Slot, Split, plan_slots

Ask = Callable[[str], str]
Say = Callable[[str], None]
CHOICES = "[a]ccept, [e]dit, [r]eject, [s]kip, [q]uit: "


def review(
    split: Split,
    reviewer: str,
    *,
    ask: Ask = input,
    say: Say = print,
    today: date | None = None,
    manual: bool = False,
    candidates_path: Path = CANDIDATES_PATH,
    seeds_path: Path = SEEDS_PATH,
) -> Counter[str]:
    """Go through the split's pending candidates (or, with `manual`, its child_safety slots).
    Returns how many were accepted, rejected and skipped."""
    today = today or date.today()
    counts: Counter[str] = Counter()
    slots = {s.id: s for s in plan_slots(split)}
    if manual:
        _review_manual(split, reviewer, slots, ask, say, today, read_seeds(seeds_path), counts)
    else:
        candidates = read_candidates(candidates_path)
        pending = [c for c in candidates if c.split == split and c.status == "pending"]
        for n, candidate in enumerate(pending, 1):
            if candidate.status != "pending":
                continue  # superseded by an earlier accept for the same slot
            if _filled(split, candidate.slot):
                candidate.status = "superseded"
                continue
            say(f"\n[{n}/{len(pending)}]")
            outcome = _review_one(candidate, slots[candidate.slot], reviewer, ask, say, today)
            counts[outcome] += 1
            if outcome == "accepted":
                for other in candidates:
                    if other.slot == candidate.slot and other.status == "pending":
                        other.status = "superseded"
            if outcome == "quit":
                break
        write_candidates(candidates, candidates_path)
    _finish(split, ask, say)
    return counts


def _review_one(
    candidate: Candidate, slot: Slot, reviewer: str, ask: Ask, say: Say, today: date
) -> str:
    text, answers, edited = candidate.text, list(candidate.answers), False
    source = (
        f"adapted from {candidate.dataset} {candidate.dataset_ref} "
        f"({DATASET_LICENCES.get(candidate.dataset or '', '?')}), reworded by {candidate.generator}"
        if candidate.origin == "adapted"
        else f"generated by {candidate.generator}"
    )
    while True:
        say(f"{slot.id} | {slot.category} | {slot.attack} | {source}")
        say(textwrap.indent(text, "    "))
        for qa in answers:
            say(f"    Q: {qa.question}\n    A: {qa.answer}")
        problem = prefilter(slot, text, answers)
        same = near_duplicates(text, known_texts())
        if same:
            problem = f"the same request as {same[0]}"
        if problem:
            say(f"  ! {problem}: edit or reject it")
        choice = ask(CHOICES).strip().lower()[:1]
        if choice == "a" and problem:
            say("  can't accept it as it is")
        elif choice == "a":
            append_item(
                slot.split,
                item_dict(
                    slot,
                    text,
                    answers,
                    origin=candidate.origin,
                    generator=candidate.generator,
                    dataset=candidate.dataset,
                    dataset_ref=candidate.dataset_ref,
                    reviewer=reviewer,
                    today=today,
                    edited=edited,
                ),
            )
            candidate.status = "accepted"
            return "accepted"
        elif choice == "e":
            text = " ".join((ask("text (Enter keeps it): ") or text).split())
            answers = [
                GeneratedQA(
                    question=ask(f"question {i} (Enter keeps it): ").strip() or qa.question,
                    answer=ask(f"answer {i} (Enter keeps it): ").strip() or qa.answer,
                )
                for i, qa in enumerate(answers, 1)
            ]
            edited = True
        elif choice == "r":
            candidate.status = "rejected"
            candidate.reason = ask("reason (optional): ").strip() or None
            return "rejected"
        elif choice == "s":
            return "skipped"
        elif choice == "q":
            return "quit"


def _review_manual(
    split: Split,
    reviewer: str,
    slots: dict[str, Slot],
    ask: Ask,
    say: Say,
    today: date,
    seeds: dict[str, Any],
    counts: Counter[str],
) -> None:
    """child_safety slots: the reviewer writes the item from a dataset seed; no model involved."""
    for slot in slots.values():
        if not slot.manual or _filled(split, slot.id):
            continue
        seed = seeds.get(slot.id)
        say(f"\n{slot.id} | {slot.category} | {slot.attack}: {ATTACK_DESCRIPTIONS[slot.attack]}")
        if seed:
            say(f"  seed from {seed.dataset} {seed.ref} ({seed.licence}):")
            say(textwrap.indent(seed.text, "    "))
        text = " ".join(ask("intent-level request (Enter skips this slot): ").split())
        if not text:
            counts["skipped"] += 1
            continue
        answers: list[GeneratedQA] = []
        while slot.attack == "two_turn" and len(answers) < 2:
            question = ask("clarifying question (Enter ends): ").strip()
            if not question:
                break
            answers.append(GeneratedQA(question=question, answer=ask("the answer: ").strip()))
        dataset = seed.dataset if seed else ask(f"dataset ({', '.join(DATASET_LICENCES)}): ")
        dataset_ref = seed.ref if seed else ask("row reference: ").strip()
        problem = prefilter(slot, text, answers)
        if dataset not in DATASET_LICENCES or not dataset_ref:
            problem = "a known dataset and a row reference are needed"
        if same := near_duplicates(text, known_texts()):
            problem = f"the same request as {same[0]}"
        if problem:
            say(f"  not accepted: {problem}")
            counts["skipped"] += 1
            continue
        append_item(
            split,
            item_dict(
                slot,
                text,
                answers,
                origin="adapted",
                generator=None,
                dataset=dataset,
                dataset_ref=dataset_ref,
                reviewer=reviewer,
                today=today,
                edited=False,
            ),
        )
        counts["accepted"] += 1


def item_dict(
    slot: Slot,
    text: str,
    answers: Sequence[GeneratedQA],
    *,
    origin: str,
    generator: str | None,
    dataset: str | None,
    dataset_ref: str | None,
    reviewer: str,
    today: date,
    edited: bool,
) -> dict[str, Any]:
    item: dict[str, Any] = {
        "id": slot.id,
        "text": text,
        "expected": "block",
        "category": slot.category,
        "attack": slot.attack,
    }
    if answers:
        item["answers"] = [{"question": a.question, "answer": a.answer} for a in answers]
    item["origin"] = origin
    if generator:
        item["generator"] = generator
    if dataset:
        item["dataset"], item["dataset_ref"] = dataset, dataset_ref
    item["reviewer"], item["reviewed_on"] = reviewer, today
    if edited:
        item["edited"] = True
    return item


def append_item(split: str, item: dict[str, Any], path: Path | None = None) -> None:
    """Add one item at the end of the file's `requests` list, keep the header comments, bump
    the patch version and refresh `source`. The new file is validated before it is written."""
    path = path or FILES[split]
    old = path.read_text(encoding="utf-8")
    block = textwrap.indent(
        yaml.safe_dump([item], allow_unicode=True, sort_keys=False, width=92), "  "
    )
    empty = re.compile(r"^requests: \[\]\s*$", re.MULTILINE)
    if empty.search(old):
        new = empty.sub(lambda _: "requests:\n" + block.rstrip("\n"), old, count=1) + "\n"
    else:
        new = old.rstrip("\n") + "\n" + block
    new = re.sub(
        r"^version: (\d+)\.(\d+)\.(\d+)",
        lambda m: f"version: {m[1]}.{m[2]}.{int(m[3]) + 1}",
        new,
        count=1,
        flags=re.MULTILINE,
    )
    parsed = SafetyFile.model_validate_json(json.dumps(yaml.safe_load(new), default=str))
    new = re.sub(
        r"^source: .*$",
        lambda _: f"source: {json.dumps(_source(split, parsed), ensure_ascii=False)}",
        new,
        count=1,
        flags=re.MULTILINE,
    )
    SafetyFile.model_validate_json(json.dumps(yaml.safe_load(new), default=str))
    path.write_text(new, encoding="utf-8")


def set_status(split: str, status: str, path: Path | None = None) -> None:
    path = path or FILES[split]
    text = path.read_text(encoding="utf-8")
    path.write_text(
        re.sub(r"^status: \w+", f"status: {status}", text, count=1, flags=re.MULTILINE),
        encoding="utf-8",
    )


def _source(split: str, parsed: SafetyFile) -> str:
    block = [r for r in parsed.requests if r.expected == "block"]
    generators = sorted({r.generator for r in block if r.generator})
    datasets = sorted({r.dataset for r in block if r.dataset})
    reviewers = sorted({r.reviewer for r in block if r.reviewer})
    parts = []
    if generators:
        parts.append(f"generated by {', '.join(generators)} (not Claude)")
    if datasets:
        named = ", ".join(f"{d} ({DATASET_LICENCES[d]})" for d in datasets)
        parts.append(f"adapted from {named}, reworded as skill requests")
    text = "; ".join(parts) + f"; every item reviewed by {', '.join(reviewers)}"
    return f"allow half written by the AI team; block half {text}" if split == "dev" else text


def _filled(split: str, slot_id: str) -> bool:
    return any(r.id == slot_id for r in load_file(split).requests)


def _finish(split: str, ask: Ask, say: Say) -> None:
    gaps = coverage_gaps(split, _items(split))
    if gaps:
        say(f"\n{FILES[split].name} still needs: " + "; ".join(gaps))
        return
    if load_file(split).status != "incomplete":
        return
    question = f"\nEvery slot of {FILES[split].name} is filled. Set status: draft? [y/N] "
    if ask(question).strip().lower().startswith("y"):
        set_status(split, "draft")
        say("status: draft. A second person's check makes it `reviewed`.")
