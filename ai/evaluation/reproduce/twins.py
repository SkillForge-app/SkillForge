"""A live report's .md is generated from its .json (AI-25): `check` verifies it still is.

`analyzer run --live` and `safety run --live` write `<stem>.md` = render_markdown(report) and
`<stem>.json` = asdict(report) plus the run folder, from the same object. So the .md must be
exactly what the .json renders to.

Any renderer that turns the .json into exactly the .md proves that. Today's renderer is tried
first (in process, fast). Only if it gives something else is the renderer at the entry's
`recorded_at` used: `git archive` of ai/ into a new folder under the temp root, run with this
interpreter in the sandbox environment (sandbox.py: no secret, no HTTP), and removed
afterwards. So a later layout change never fails an old report.

A section added by hand after the generated part (e.g. safety-all-2026-11-17's "Completion")
must be declared in the entry's `md_addendum`, with its reason. It can only follow the generated
part, never change it. E8 (kind rescore) was written by a one-off script with no renderer in the
repo, and offline reports are re-generated by `reproduce run`: neither is checked here.
"""

import dataclasses
import importlib
import io
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path
from typing import Any

from core.spec import Issue
from evaluation.reproduce.registry import TEMP_ROOT, Entry
from evaluation.reproduce.sandbox import UnsafeTree, refuse_env_file, sandbox_env
from evaluation.reproduce.strict import DuplicateKeyError, loads_unique

RENDERERS = {
    "analyzer": ("evaluation.analyzer.evaluate", "EvalReport"),
    "safety": ("evaluation.safety.evaluate", "SafetyReport"),
}
# Run in the tree at recorded_at: the .json must hold exactly the report's fields plus `run`.
_SCRIPT = """
import dataclasses, importlib, json, sys
module = importlib.import_module(sys.argv[1])
cls = getattr(module, sys.argv[2])
data = json.loads(sys.stdin.buffer.read().decode("utf-8"))
names = {f.name for f in dataclasses.fields(cls)}
if set(data) != names | {"run"}:
    sys.exit(3)
sys.stdout.buffer.write(module.render_markdown(cls(**{k: data[k] for k in names})).encode("utf-8"))
"""


def area_of(entry: Entry) -> str | None:
    """The evaluation whose renderer wrote this entry's .md, or None (not checked here)."""
    parts = entry.report.split("/")
    if entry.kind != "live" or len(parts) != 5 or parts[3] != "reports":
        return None
    return parts[2] if parts[2] in RENDERERS else None


def render_current(area: str, data: dict[str, Any]) -> str | None:
    module = importlib.import_module(RENDERERS[area][0])
    cls = getattr(module, RENDERERS[area][1])
    names = {f.name for f in dataclasses.fields(cls)}
    if set(data) != names | {"run"}:
        return None
    try:
        return str(module.render_markdown(cls(**{k: data[k] for k in names})))
    except (AttributeError, KeyError, TypeError, ValueError):
        return None


def render_at(repo: Path, commit: str, area: str, json_text: str) -> str | None:
    """The .md the renderer at `commit` makes of `json_text`; None if it can't."""
    TEMP_ROOT.mkdir(parents=True, exist_ok=True)
    folder = Path(tempfile.mkdtemp(prefix="md-", dir=TEMP_ROOT))  # removed below: ours only
    try:
        tar = subprocess.run(
            ["git", "-c", "core.autocrlf=false", "archive", "--format=tar", commit, "ai"],
            cwd=repo,
            capture_output=True,
        )
        if tar.returncode != 0:
            return None
        with tarfile.open(fileobj=io.BytesIO(tar.stdout)) as archive:
            archive.extractall(folder, filter="data")
        tree = folder / "ai"
        refuse_env_file(tree)
        proc = subprocess.run(
            [sys.executable, "-c", _SCRIPT, *RENDERERS[area]],
            cwd=tree,
            input=json_text.encode("utf-8"),
            capture_output=True,
            # old-commit code: no secret, no HTTP (sandbox.py), the fake backend
            env=sandbox_env(extra={"PYTHONPATH": str(tree), "PYTHONDONTWRITEBYTECODE": "1"}),
        )
        return proc.stdout.decode("utf-8") if proc.returncode == 0 else None
    finally:
        shutil.rmtree(folder, ignore_errors=True)


def _matches(rendered: str | None, md: str, addendum: str | None) -> bool:
    if rendered is None:
        return False
    if addendum is None:
        return md == rendered
    rest = md[len(rendered) :] if md.startswith(rendered) else ""
    return rest.startswith("\n## ")  # a declared section after the generated part, nothing else


def markdown_issues(entry: Entry, repo: Path) -> list[Issue]:
    area = area_of(entry)
    json_path = repo / entry.report
    md_path = json_path.with_suffix(".md")
    if area is None or not json_path.is_file() or not md_path.is_file():
        return []  # a missing .md is reported by check itself
    json_text = json_path.read_text(encoding="utf-8").replace("\r\n", "\n")
    md = md_path.read_text(encoding="utf-8").replace("\r\n", "\n")
    try:
        data = loads_unique(json_text)
    except DuplicateKeyError:
        return []  # reported by check itself
    if _matches(render_current(area, data), md, entry.md_addendum):
        return []
    try:
        old = render_at(repo, entry.recorded_at, area, json_text)
    except UnsafeTree as exc:
        return [Issue(entry.id, "unsafe_tree", str(exc))]
    if _matches(old, md, entry.md_addendum):
        return []
    extra = " (plus its declared md_addendum)" if entry.md_addendum else ""
    return [
        Issue(
            entry.id,
            "markdown_mismatch",
            f"{md_path.name} is not what {json_path.name} renders to{extra}",
        )
    ]


__all__ = ["area_of", "markdown_issues", "render_at", "render_current"]
